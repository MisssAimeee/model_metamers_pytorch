"""
Cross-model recognizability evaluation for AV metamers.

Tests whether metamers generated by deep_avsr are recognisable to a second,
independent feature extractor.  Two feature spaces are compared:

  deep_avsr  : the model used to synthesize the metamers (from comparison.csv)
  MFCC       : 40-coefficient log-MFCC — a classic perceptual proxy
  Wav2Vec2   : if `transformers` is installed; Facebook's SSL speech model
               gives a strong "human-like" speech feature baseline

Interpretation guide
--------------------
  Low deep_avsr dist, low MFCC dist   → shared / perceptual invariances
  Low deep_avsr dist, high MFCC dist  → idiosyncratic (model-specific) invariances
  The scatter-plot in cross_model_scatter.png visualises this directly.

Outputs to --out-dir:
  cross_model_results.csv     per-clip distances in all feature spaces
  cross_model_stats.json      summary & correlation between feature spaces
  cross_model_scatter.png     scatter: deep_avsr dist vs MFCC / W2V2 dist

Usage:
    cd /home/aimeeyu/mms_project
    python eval_cross_model.py \\
        --results-dir model_metamers_pytorch/results/av_metamers_42_natural \\
        --stimuli-dir model_metamers_pytorch/stimuli/MUSHRA_42_NATURAL \\
        --out-dir     model_metamers_pytorch/results/cross_model_eval
"""

import sys, os, csv, json, math, argparse
from pathlib import Path

_MMS_PY = "/home/aimeeyu/.conda/envs/mms/bin/python"
if Path(_MMS_PY).exists() and Path(sys.executable).resolve() != Path(_MMS_PY).resolve():
    print(f"[bootstrap] re-execing under {_MMS_PY}")
    os.execv(_MMS_PY, [_MMS_PY, *sys.argv])

import numpy as np
import torch
import torchaudio
import torchaudio.transforms as T
from scipy.io import wavfile
import scipy.signal as scisig

REPO_ROOT = Path(__file__).parent
if (REPO_ROOT / "deep_avsr").exists():
    _RESULTS_BASE = REPO_ROOT / "results"
    _STIMULI_BASE = REPO_ROOT / "stimuli"
else:
    _RESULTS_BASE = REPO_ROOT / "model_metamers_pytorch" / "results"
    _STIMULI_BASE = REPO_ROOT / "model_metamers_pytorch" / "stimuli"
TARGET_SR = 16_000

MFCC_N_MFCC    = 40
MFCC_N_FFT     = 400
MFCC_HOP       = 160
MFCC_N_MELS    = 80


# ─────────────────────────────────────────────────────────────────────────────
# Category helper
# ─────────────────────────────────────────────────────────────────────────────

def category_from_stim(stim_folder: str) -> str:
    s = stim_folder.lower()
    speech_keys = ["speaking", "spanish", "french", "italian", "german", "hindi", "russian", "vocal"]
    music_keys  = ["bluegrass", "violin", "cello", "jazz", "saxophone", "orchestra", "piano",
                   "contemporary_rb", "band_music", "latin_music", "country_song", "rap_music",
                   "acoustic_guitar"]
    if any(k in s for k in speech_keys):
        return "speech"
    if any(k in s for k in music_keys):
        return "music"
    return "environment"


# ─────────────────────────────────────────────────────────────────────────────
# Audio loading
# ─────────────────────────────────────────────────────────────────────────────

def load_wav_tensor(wav_path: Path) -> torch.Tensor:
    """Load wav → float32 tensor, resample to TARGET_SR, shape (1, T)."""
    sr, data = wavfile.read(str(wav_path))
    data = data.astype(np.float32)
    if data.ndim == 2:
        data = data.mean(axis=1)
    if sr != TARGET_SR:
        g = math.gcd(sr, TARGET_SR)
        data = scisig.resample_poly(data, TARGET_SR // g, sr // g).astype(np.float32)
    maxval = np.abs(data).max()
    if maxval > 0:
        data = data / maxval
    return torch.from_numpy(data).unsqueeze(0)   # (1, T)


# ─────────────────────────────────────────────────────────────────────────────
# MFCC feature extractor
# ─────────────────────────────────────────────────────────────────────────────

class MFCCExtractor:
    def __init__(self, sample_rate: int = TARGET_SR):
        self.mfcc = T.MFCC(
            sample_rate=sample_rate,
            n_mfcc=MFCC_N_MFCC,
            melkwargs={
                "n_fft":     MFCC_N_FFT,
                "hop_length": MFCC_HOP,
                "n_mels":    MFCC_N_MELS,
                "f_min":     80.0,
                "f_max":     7600.0,
            },
        )

    @torch.no_grad()
    def __call__(self, wav: torch.Tensor) -> np.ndarray:
        """wav : (1, T)  → 1-D numpy feature vector (mean-pooled MFCCs + delta)."""
        mfcc = self.mfcc(wav)   # (1, n_mfcc, T)
        # delta and delta-delta for richer representation
        d1 = T.ComputeDeltas()(mfcc)
        d2 = T.ComputeDeltas()(d1)
        feat = torch.cat([mfcc, d1, d2], dim=1)   # (1, 3*n_mfcc, T)
        # Mean and std pooling over time
        mean_feat = feat.mean(dim=-1).squeeze(0)    # (3*n_mfcc,)
        std_feat  = feat.std(dim=-1).squeeze(0)
        return torch.cat([mean_feat, std_feat]).numpy()   # (6*n_mfcc,)


def cosine_dist(a: np.ndarray, b: np.ndarray) -> float:
    norm_a = np.linalg.norm(a)
    norm_b = np.linalg.norm(b)
    if norm_a < 1e-8 or norm_b < 1e-8:
        return 1.0
    return float(1.0 - np.dot(a, b) / (norm_a * norm_b))


def l2_dist(a: np.ndarray, b: np.ndarray) -> float:
    num = np.linalg.norm(a - b)
    den = np.linalg.norm(b) + 1e-8
    return float(num / den)


# ─────────────────────────────────────────────────────────────────────────────
# Optional Wav2Vec2 extractor
# ─────────────────────────────────────────────────────────────────────────────

def try_load_wav2vec2():
    """Return a (model, feature_fn) tuple or (None, None) if unavailable."""
    try:
        from transformers import Wav2Vec2Model, Wav2Vec2FeatureExtractor
        print("[cross-model] Loading Wav2Vec2 from HuggingFace …")
        extractor = Wav2Vec2FeatureExtractor.from_pretrained("facebook/wav2vec2-base")
        model     = Wav2Vec2Model.from_pretrained("facebook/wav2vec2-base")
        model.eval()
        print("[cross-model] Wav2Vec2 loaded.\n")

        @torch.no_grad()
        def extract_w2v(wav: torch.Tensor) -> np.ndarray:
            # wav: (1, T) float32
            inputs = extractor(
                wav.squeeze(0).numpy(),
                sampling_rate=TARGET_SR,
                return_tensors="pt",
            )
            out = model(**inputs).last_hidden_state   # (1, T', 768)
            feat = out.mean(dim=1).squeeze(0).numpy()  # (768,)
            return feat

        return model, extract_w2v
    except Exception as exc:
        print(f"[cross-model] Wav2Vec2 unavailable ({exc}). Using MFCC only.\n")
        return None, None


# ─────────────────────────────────────────────────────────────────────────────
# CLI
# ─────────────────────────────────────────────────────────────────────────────

def parse_args():
    p = argparse.ArgumentParser(description="Cross-model recognizability evaluation")
    p.add_argument("--results-dir", type=Path,
                   default=_RESULTS_BASE / "av_metamers_42_natural")
    p.add_argument("--stimuli-dir", type=Path,
                   default=_STIMULI_BASE / "MUSHRA_42_NATURAL")
    p.add_argument("--out-dir", type=Path,
                   default=_RESULTS_BASE / "cross_model_eval")
    p.add_argument("--no-wav2vec2", action="store_true",
                   help="Skip Wav2Vec2 even if transformers is available")
    p.add_argument("--no-plot", action="store_true")
    return p.parse_args()


# ─────────────────────────────────────────────────────────────────────────────
# Main
# ─────────────────────────────────────────────────────────────────────────────

def main():
    args = parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    # ── Load comparison.csv ───────────────────────────────────────────────────
    csv_path = args.results_dir / "comparison.csv"
    entries  = []
    with csv_path.open(newline="") as f:
        for row in csv.DictReader(f):
            entries.append(dict(row))
    print(f"Loaded {len(entries)} entries from {csv_path}\n")

    # ── Feature extractors ────────────────────────────────────────────────────
    mfcc_fn = MFCCExtractor()

    w2v_model, w2v_fn = (None, None)
    if not args.no_wav2vec2:
        w2v_model, w2v_fn = try_load_wav2vec2()

    # ── Process each entry ────────────────────────────────────────────────────
    results = []
    for idx, entry in enumerate(entries):
        stim_folder  = entry["stim_folder"]
        wav_file     = entry["wav_file"]
        metamer_wav  = Path(entry["metamer_wav"])
        avsr_dist    = float(entry["match_distance"])
        category     = category_from_stim(stim_folder)

        # Locate original wav
        orig_wav = args.stimuli_dir / stim_folder / wav_file
        if not orig_wav.exists():
            candidates = list(args.stimuli_dir.glob(f"**/{wav_file}"))
            orig_wav   = candidates[0] if candidates else None
        if orig_wav is None or not orig_wav.exists():
            print(f"  [warn] original not found: {wav_file} — skip")
            continue
        if not metamer_wav.exists():
            print(f"  [warn] metamer not found: {metamer_wav} — skip")
            continue

        print(f"  [{idx+1}/{len(entries)}] {stim_folder}/{wav_file}")

        orig_wav_t = load_wav_tensor(orig_wav)
        met_wav_t  = load_wav_tensor(metamer_wav)

        # MFCC distance
        orig_mfcc = mfcc_fn(orig_wav_t)
        met_mfcc  = mfcc_fn(met_wav_t)
        mfcc_cos  = cosine_dist(orig_mfcc, met_mfcc)
        mfcc_l2   = l2_dist(orig_mfcc, met_mfcc)

        row = {
            "stim_folder":   stim_folder,
            "wav_file":      wav_file,
            "category":      category,
            "avsr_dist":     f"{avsr_dist:.6f}",
            "mfcc_cosine":   f"{mfcc_cos:.6f}",
            "mfcc_l2":       f"{mfcc_l2:.6f}",
            "w2v2_cosine":   "",
            "w2v2_l2":       "",
        }

        # Optional Wav2Vec2
        if w2v_fn is not None:
            try:
                orig_w2v = w2v_fn(orig_wav_t)
                met_w2v  = w2v_fn(met_wav_t)
                row["w2v2_cosine"] = f"{cosine_dist(orig_w2v, met_w2v):.6f}"
                row["w2v2_l2"]     = f"{l2_dist(orig_w2v, met_w2v):.6f}"
            except Exception as exc:
                print(f"    [warn] w2v2 failed: {exc}")

        results.append(row)

    # ── Save CSV ──────────────────────────────────────────────────────────────
    out_csv = args.out_dir / "cross_model_results.csv"
    fields  = ["stim_folder", "wav_file", "category",
               "avsr_dist", "mfcc_cosine", "mfcc_l2", "w2v2_cosine", "w2v2_l2"]
    with out_csv.open("w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=fields)
        wr.writeheader()
        wr.writerows(results)
    print(f"\nResults CSV → {out_csv}")

    # ── Summary statistics ────────────────────────────────────────────────────
    import statistics as _stat
    from scipy import stats as sp_stats

    avsr_vals  = [float(r["avsr_dist"])  for r in results]
    mfcc_l2s   = [float(r["mfcc_l2"])   for r in results]
    mfcc_coss  = [float(r["mfcc_cosine"]) for r in results]

    corr_mfcc, p_mfcc = sp_stats.pearsonr(avsr_vals, mfcc_l2s)

    summary = {
        "n": len(results),
        "avsr_mean":   _stat.mean(avsr_vals),
        "mfcc_l2_mean": _stat.mean(mfcc_l2s),
        "mfcc_cosine_mean": _stat.mean(mfcc_coss),
        "pearsonr_avsr_vs_mfcc_l2": float(corr_mfcc),
        "pearsonr_p": float(p_mfcc),
        "interpretation": (
            "Positive correlation (r>0.4) → both models agree on distance, "
            "suggesting shared/perceptual invariances. "
            "Near-zero or negative correlation → model-specific invariances."
        ),
        "per_category": {},
    }

    print(f"\n{'─'*55}")
    print(f"  Overall  AVSR mean={_stat.mean(avsr_vals):.4f}  "
          f"MFCC-L2 mean={_stat.mean(mfcc_l2s):.4f}")
    print(f"  Pearson r(AVSR, MFCC-L2) = {corr_mfcc:.3f}  (p={p_mfcc:.3e})")

    for cat in ["environment", "music", "speech"]:
        cat_rows  = [r for r in results if r["category"] == cat]
        if not cat_rows:
            continue
        a = [float(r["avsr_dist"]) for r in cat_rows]
        m = [float(r["mfcc_l2"])   for r in cat_rows]
        cr, cp = sp_stats.pearsonr(a, m) if len(a) > 2 else (float("nan"), float("nan"))
        print(f"  [{cat}]  AVSR={_stat.mean(a):.4f}  MFCC={_stat.mean(m):.4f}  r={cr:.3f}")
        summary["per_category"][cat] = {
            "n": len(a), "avsr_mean": float(_stat.mean(a)),
            "mfcc_l2_mean": float(_stat.mean(m)), "pearsonr": float(cr), "pearsonr_p": float(cp),
        }

    w2v2_vals = [float(r["w2v2_l2"]) for r in results if r["w2v2_l2"]]
    if w2v2_vals:
        corr_w2v, p_w2v = sp_stats.pearsonr(
            [float(r["avsr_dist"]) for r in results if r["w2v2_l2"]],
            w2v2_vals,
        )
        print(f"  Pearson r(AVSR, Wav2Vec2-L2) = {corr_w2v:.3f}  (p={p_w2v:.3e})")
        summary["pearsonr_avsr_vs_w2v2_l2"] = float(corr_w2v)
        summary["pearsonr_w2v2_p"] = float(p_w2v)
        summary["w2v2_l2_mean"] = float(_stat.mean(w2v2_vals))

    print(f"{'─'*55}")

    stats_path = args.out_dir / "cross_model_stats.json"
    stats_path.write_text(json.dumps(summary, indent=2))
    print(f"Stats JSON → {stats_path}")

    # ── Scatter plot ──────────────────────────────────────────────────────────
    if not args.no_plot:
        try:
            import matplotlib
            matplotlib.use("Agg")
            import matplotlib.pyplot as plt

            cat_colors = {"environment": "#4CAF50", "music": "#2196F3", "speech": "#FF5722"}
            n_plots = 2 if w2v2_vals else 1
            fig, axes = plt.subplots(1, n_plots, figsize=(7 * n_plots, 6))
            if n_plots == 1:
                axes = [axes]

            def scatter_panel(ax, x_vals, y_vals, xlabel, title, cats):
                for cat in ["environment", "music", "speech"]:
                    mask = [i for i, c in enumerate(cats) if c == cat]
                    xs   = [x_vals[i] for i in mask]
                    ys   = [y_vals[i] for i in mask]
                    ax.scatter(xs, ys, c=cat_colors[cat], label=cat, alpha=0.7, s=50)
                # Regression line
                if len(x_vals) > 2:
                    m_fit, b_fit = np.polyfit(x_vals, y_vals, 1)
                    xs_line = np.linspace(min(x_vals), max(x_vals), 100)
                    ax.plot(xs_line, m_fit * xs_line + b_fit, "k--", lw=1, alpha=0.6)
                ax.set_xlabel("deep_avsr activation distance", fontsize=11)
                ax.set_ylabel(xlabel, fontsize=11)
                ax.set_title(title, fontsize=12)
                ax.legend(fontsize=9)
                corr, _ = sp_stats.pearsonr(x_vals, y_vals)
                ax.text(0.05, 0.95, f"r = {corr:.3f}", transform=ax.transAxes,
                        fontsize=10, va="top")

            cats_list = [r["category"] for r in results]
            scatter_panel(
                axes[0], avsr_vals, mfcc_l2s,
                "MFCC L2 distance",
                "deep_avsr vs MFCC distance\n(near-zero r = model-specific invariances)",
                cats_list,
            )
            if w2v2_vals:
                avsr_w2v = [float(r["avsr_dist"]) for r in results if r["w2v2_l2"]]
                cats_w2v = [r["category"] for r in results if r["w2v2_l2"]]
                scatter_panel(
                    axes[1], avsr_w2v, w2v2_vals,
                    "Wav2Vec2 L2 distance",
                    "deep_avsr vs Wav2Vec2 distance",
                    cats_w2v,
                )

            fig.suptitle(
                "Cross-model recognizability: deep_avsr metamers\n"
                "Low deep_avsr + high other-model = idiosyncratic invariances",
                fontsize=11,
            )
            plt.tight_layout()
            plot_path = args.out_dir / "cross_model_scatter.png"
            plt.savefig(plot_path, dpi=150)
            plt.close(fig)
            print(f"Scatter plot → {plot_path}")
        except Exception as exc:
            print(f"[warn] plot failed: {exc}")

    print("\nDone.")


if __name__ == "__main__":
    main()
